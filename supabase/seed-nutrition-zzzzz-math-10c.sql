--   3. qualifier foods     one USDA food per (ingredient, qualifier form), generated from
--                          scripts/nutrition/review/qualifier-foods-10c.csv
--   4. size factors        "large"/"small" scale an each-weight by the USDA portion ratio, per ingredient, generated from
