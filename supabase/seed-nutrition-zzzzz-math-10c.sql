select 'form', r.pattern, null, r.form, r.strict, r.satisfied_by, r.priority, r.note
from   _rule r
where  not exists (select 1 from prep_rules p where p.kind = 'form' and p.ingredient_id is null and p.pattern = r.pattern and p.form = r.form);

