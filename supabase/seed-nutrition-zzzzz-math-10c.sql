create temp table _target on commit drop as
select f.*, ri.id as ri_id, ri.recipe_id
from   _fix f
join   recipes r on regexp_replace(r.source_url, '^.*/recipes/', '') = f.slug and r.source_name like 'USDA MyPlate%'
join   recipe_ingredients ri on ri.recipe_id = r.id and ri.sort_order = f.ord
join   ingredients cur on cur.id = ri.ingredient_id
where  cur.canonical_name = f.ingredient or (f.action = 'ingredient' and cur.canonical_name = f.new_value);

-- prep note: set only when the stored note still has the value the audit saw (a later edit by hand wins)
update recipe_ingredients ri
   set prep_note = nullif(t.new_value, '')
  from _target t
 where t.action = 'note' and ri.id = t.ri_id
   and ri.prep_note is not distinct from nullif(t.old_value, '');

-- another canonical ingredient (fat-free milk is skim milk): the line keeps its amount and note
update recipe_ingredients ri
   set ingredient_id = n.id
  from _target t
  join ingredients n on n.canonical_name = t.new_value
 where t.action = 'ingredient' and ri.id = t.ri_id
   and ri.ingredient_id = (select id from ingredients where canonical_name = t.old_value);

-- an amount the importer dropped or got wrong ("1 package (10 ounces)" -> 10 oz; "4 (6 ounces each) fillets" -> 24 oz).
-- old_value '' = the line has no amount; otherwise "<quantity> <unit>" ('<quantity>' alone for an each-count) must still match.
update recipe_ingredients ri
   set quantity = split_part(t.new_value, ' ', 1)::numeric,
       unit_id  = (select u.id from units u where u.name = nullif(substr(t.new_value, length(split_part(t.new_value, ' ', 1)) + 2), ''))
  from _target t
 where t.action = 'qty_unit' and ri.id = t.ri_id
   and (case when t.old_value = '' then ri.quantity is null
             else ri.quantity = split_part(t.old_value, ' ', 1)::numeric
                  and coalesce((select u.name from units u where u.id = ri.unit_id), '') = coalesce(substr(t.old_value, length(split_part(t.old_value, ' ', 1)) + 2), '') end)
   and (nullif(substr(t.new_value, length(split_part(t.new_value, ' ', 1)) + 2), '') is null
        or exists (select 1 from units u where u.name = substr(t.new_value, length(split_part(t.new_value, ' ', 1)) + 2)));

-- the later options of an "A or B" line: the first option carries the amount, the rest are alternatives
update recipe_ingredients ri
   set is_optional = true
  from _target t
 where t.action = 'optional' and ri.id = t.ri_id and not ri.is_optional;

-- a row that only existed because of a mis-parse (the same peas twice)
delete from recipe_ingredients ri
 using _target t
 where t.action = 'delete' and ri.id = t.ri_id;

commit;
