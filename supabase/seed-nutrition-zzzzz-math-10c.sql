-- "2 cups cooked rice" with no cooked rice food, "1 can" of something with no canned food: a named gap, not the dry / fresh food
update prep_rules
   set strict = true,
       satisfied_by = '\m(cooked|boiled|baked|roasted|broiled|grilled|fried|steamed|poached|braised|stewed|canned|prepared|pre-?cooked|rotisserie|ready[- ]to[- ](eat|serve))\M',
       note = 'proposed: a line that says cooked needs a cooked food; a default that already is cooked (description says so) satisfies it. Wave 10c: strict.'
 where kind = 'form' and form = 'cooked' and ingredient_id is null and pattern = '\mcooked\M';

update prep_rules
   set strict = true,
       satisfied_by = '\m(canned|jarred|bottled|solids and liquids|drained solids|packed in|in (water|juice|syrup|brine|oil))\M',
       note = 'proposed: a line that says canned (or counts cans) needs a canned food; a default that already is canned satisfies it. Wave 10c: strict.'
 where kind = 'form' and form = 'canned' and ingredient_id is null and pattern = '\m(canned|cans?)\M';

-- fat-free mayonnaise is its own food now; the 'light' form keeps light / reduced fat / low fat
update prep_rules
   set pattern = '\m(light|lite|low[- ]?fat|reduced[- ]?(fat|calorie))\M'
 where kind = 'form' and form = 'light'
   and ingredient_id = (select id from ingredients where canonical_name = 'mayonnaise')
   and pattern like '%fat[- ]?free%';

create temp table _rule (pattern text, form text, strict boolean, satisfied_by text, priority integer, note text) on commit drop;
insert into _rule values
  ('\m(low[- ]sodium|reduced[- ]sodium|lower[- ]sodium|less sodium|no[- ]salt[- ]added|salt[- ]free)\M', 'low_sodium', true,
   '(low|reduced|less|lower)[ /-]*(or )?(reduced )?sodium|no salt added|without salt|unsalted|salt[ -]free',
   10, 'wave 10c: a low-sodium line needs a low-sodium food; sodium is what the qualifier changes'),
  ('\m(fat[- ]free|non-?fat)\M|(?<!part[- ])\mskim\M', 'fat_free', true, 'fat[- ]free|nonfat|non-fat|skim',
