-- link the food (default for its form), demoting any other default of that form
insert into ingredient_foods (ingredient_id, form, fdc_id, is_default)
select i.id, q.form, q.fdc_id, false
from   _q q join ingredients i on i.canonical_name = q.ingredient
where  exists (select 1 from usda_foods u where u.fdc_id = q.fdc_id)
on conflict (ingredient_id, form, fdc_id) do nothing;
update ingredient_foods f set is_default = false
from   _q q join ingredients i on i.canonical_name = q.ingredient
where  f.ingredient_id = i.id and f.form = q.form and f.fdc_id <> q.fdc_id and f.is_default
  and  exists (select 1 from ingredient_foods g where g.ingredient_id = i.id and g.form = q.form and g.fdc_id = q.fdc_id);
update ingredient_foods f set is_default = true
from   _q q join ingredients i on i.canonical_name = q.ingredient
where  f.ingredient_id = i.id and f.form = q.form and f.fdc_id = q.fdc_id and not f.is_default;

-- weights: a qualifier form weighs what the default form weighs (a cup of fat-free yogurt is a cup of yogurt), and
-- the ingredient's density fills the volume units the default form has no row for
insert into ingredient_portions (ingredient_id, form, unit_id, grams_per_unit, source, note)
select i.id, q.form, p.unit_id, p.grams_per_unit, p.source, 'copied from the ' || p.form || ' form (wave 10c)'
from   _q q
join   ingredients i on i.canonical_name = q.ingredient
join   ingredient_portions p on p.ingredient_id = i.id and p.form = case when q.copy_portions = 'yes' then 'default' else q.copy_portions end
where  q.copy_portions <> 'no'
  and  exists (select 1 from ingredient_foods f where f.ingredient_id = i.id and f.form = q.form)
on conflict (ingredient_id, form, (coalesce(unit_id, 0))) do nothing;
insert into ingredient_portions (ingredient_id, form, unit_id, grams_per_unit, source, note)
select i.id, q.form, u.id, round(i.density_g_per_ml * u.to_base_factor, 2), 'curated', 'from the ingredient density (wave 10c)'
from   _q q
join   ingredients i on i.canonical_name = q.ingredient and i.density_g_per_ml is not null
cross  join units u
where  q.copy_portions = 'yes' and u.name in ('cup', 'tbsp', 'tsp', 'fl oz')
  and  exists (select 1 from ingredient_foods f where f.ingredient_id = i.id and f.form = q.form)
on conflict (ingredient_id, form, (coalesce(unit_id, 0))) do nothing;

