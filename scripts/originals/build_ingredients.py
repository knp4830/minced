#!/usr/bin/env python3
"""Build supabase/seed-ingredients-w12.sql: the NEW canonical ingredients the wave-12 original recipes need,
each with a real USDA FoodData Central food (CC0), allergen tags, density and aliases.

    python -I scripts/originals/build_ingredients.py          # uses scripts/originals/cache/*.json, fetches if missing

Rules (docs/LESSONS.md section 11): a food is a real FDC id, never an average; missing is not zero; label-rounded zeros
for vitamins and minerals are NOT stored (only a true zero we can justify from the ingredient list: cholesterol and
trans fat of a plant-only product). Aliases are cook phrasings; no simple plurals.
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
HERE = Path(__file__).resolve().parent
CACHE = HERE / "cache"
CACHE.mkdir(exist_ok=True)
OUT = ROOT / "supabase" / "seed-ingredients-w12.sql"

# FDC nutrient number -> our nutrients.id (from the nutrients table)
NUM2ID = {"208": 1, "203": 2, "205": 3, "291": 4, "269": 5, "204": 7, "606": 8, "605": 9, "645": 10, "646": 11,
          "601": 12, "307": 13, "306": 14, "301": 15, "303": 16, "304": 17, "309": 18, "305": 19, "317": 20,
          "312": 21, "315": 22, "401": 24, "328": 25, "323": 26, "430": 27, "404": 28, "405": 29, "406": 30,
          "415": 31, "418": 33, "410": 34, "421": 35, "324": 90}
# true zeros we can justify from the ingredient list of a plant-only product
TRUE_ZERO_OK = {"601", "605"}

SPECS = [
    {
        "name": "chunjang", "slug": "chunjang", "aisle": "Pantry", "filter_group": "pantry", "diet_class": "plant",
        "aliases": ["korean black bean paste", "jajang paste", "chungjang"],
        "allergens": [("gluten", "typical", "wheat flour and soybean powder"),
                      ("soy", "typical", "wheat flour and soybean powder"),
                      ("wheat", "typical", "wheat flour and soybean powder")],
        "density": 1.2,  # g/ml, the catalog convention for fermented bean pastes (doubanjiang, gochujang)
        "fdc_id": 2010198,
        "why": "ASSI black bean paste (Korean roasted black bean paste: water, wheat flour, caramel, soybean powder, salt)",
    },
]


def fetch(fdc_id: int) -> dict:
    p = CACHE / f"{fdc_id}.json"
    if not p.exists():
        out = subprocess.run([sys.executable, "-I", str(HERE / "fdc_search.py"), "--raw", str(fdc_id)],
                             capture_output=True, text=True, encoding="utf-8")
        if out.returncode:
            sys.exit(out.stderr)
        p.write_text(out.stdout, encoding="utf-8")
    return json.loads(p.read_text(encoding="utf-8"))


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def main() -> int:
    lines = [
        "-- GENERATED by scripts/originals/build_ingredients.py -- do not edit. IDEMPOTENT.",
        "-- Wave 12 (cuisines lane): new canonical ingredients needed by supabase/seed-originals-w12.sql, each with a real",
        "-- USDA FoodData Central food (CC0). Run AFTER seed-allergen-tags.sql and BEFORE seed-originals-w12.sql.",
        "-- seed-allergen-tags.sql refuses to run if an ingredient is missing from its table; this file carries its own tags.",
        "begin;",
    ]
    for s in SPECS:
        d = fetch(s["fdc_id"])
        desc = d["description"]
        brand_name = desc.split(",")[0].title() if "," in desc else (d.get("brandName") or None)
        pub = (d.get("publicationDate") or d.get("modifiedDate") or "")
        # publicationDate comes as MM/DD/YYYY
        if "/" in pub:
            m, dd, y = pub.split("/")
            pub = f"{y}-{m}-{dd}"
        lines += [
            f"-- {s['name']}: {s['why']} (FDC {s['fdc_id']})",
            "insert into ingredients (canonical_name, slug, aisle_category, is_pantry_staple, filter_group, diet_class, density_g_per_ml)",
            f"values ({q(s['name'])}, {q(s['slug'])}, {q(s['aisle'])}, false, {q(s['filter_group'])}, {q(s['diet_class'])}, {s['density']})",
            "on conflict (canonical_name) do nothing;",
            "insert into ingredient_aliases (ingredient_id, alias)",
            "select i.id, a.alias from ingredients i, (values " + ", ".join(f"({q(a)})" for a in s["aliases"]) +
            f") a(alias) where i.canonical_name = {q(s['name'])}",
            "on conflict (alias) do nothing;",
            "insert into ingredient_allergens (ingredient_id, allergen_id, basis, reason)",
            "select i.id, al.id, v.basis, v.reason from ingredients i, (values " +
            ", ".join(f"({q(a)}, {q(b)}, {q(r)})" for a, b, r in s["allergens"]) +
            f") v(slug, basis, reason) join allergens al on al.slug = v.slug where i.canonical_name = {q(s['name'])}",
            "on conflict (ingredient_id, allergen_id) do nothing;",
            "insert into usda_foods (fdc_id, description, data_type, brand_owner, brand_name, serving_size, serving_size_unit, household_serving, publication_date)",
            f"values ({s['fdc_id']}, {q(desc)}, 'branded', {q(d.get('brandOwner') or '')}, {q(brand_name) if brand_name else 'null'}, "
            f"{d.get('servingSize')}, {q(str(d.get('servingSizeUnit') or 'g').lower())}, {q(d.get('householdServingFullText') or '')}, "
            f"{q(pub) if pub else 'null'})",
            "on conflict (fdc_id) do nothing;",
        ]
        vals = []
        for n in d["foodNutrients"]:
            num = n["nutrient"]["number"]
            amt = n.get("amount")
            if num not in NUM2ID or amt is None:
                continue
            if amt == 0 and num not in TRUE_ZERO_OK:
                continue  # label-rounded zero: not reported, not a true zero
            vals.append(f"({s['fdc_id']}, {NUM2ID[num]}, {amt})")
        lines += ["insert into usda_food_nutrients (fdc_id, nutrient_id, amount_per_100g) values", "  " + ",\n  ".join(vals),
                  "on conflict (fdc_id, nutrient_id) do nothing;"]
        lines += [
            "insert into ingredient_foods (ingredient_id, form, fdc_id, is_default)",
            f"select i.id, 'default', {s['fdc_id']}, true from ingredients i where i.canonical_name = {q(s['name'])}",
            "on conflict do nothing;",
        ]
    lines += ["commit;", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
