#!/usr/bin/env python3
"""Build the wave-12 "Minced original" seed from hand-written recipe files.

    python scripts/originals/build.py

Reads   scripts/originals/recipes/*.txt     recipes in Minced's own words (format: see header of korean.txt)
        scripts/originals/sources/*.tsv     verification URLs (review only, never stored in the database)
        scripts/originals/cuisines.txt      new cuisine names (one per line)
Writes  supabase/seed-originals-w12.sql
        docs/content/RECIPE-REVIEW-w12.md

Differences from scripts/content/build_original.py (wave 1):
  * recipes land as status 'in_review' (the admin queue publishes them on approval); never 'published'
  * NEW SLUGS ONLY: an existing slug is skipped, never updated, so a reviewer's edits or an approval are never undone
  * diets/allergens come from the wave 10c pipeline (refresh_recipe_allergens / refresh_recipe_diets), not a local derivation
  * nutrition is computed in the same transaction (refresh_recipe_nutrients), never typed
  * the same strict gates: exact/alias ingredient resolution only, unknown unit/cuisine/cookware aborts, title dedupe
"""
from __future__ import annotations

import importlib.util
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("bo", ROOT / "scripts" / "content" / "build_original.py")
bo = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bo)  # reuse parse_recipes / validate / helpers
bo.RECIPE_DIR = HERE / "recipes"
bo.SOURCE_DIR = HERE / "sources"

OUT_SQL = ROOT / "supabase" / "seed-originals-w12.sql"
OUT_REVIEW = ROOT / "docs" / "content" / "RECIPE-REVIEW-w12.md"
SOURCE_NAME = bo.SOURCE_NAME
SOURCE_LICENSE = bo.SOURCE_LICENSE


def slugify(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def new_cuisines() -> list[str]:
    p = HERE / "cuisines.txt"
    return [l.strip() for l in p.read_text(encoding="utf-8").splitlines() if l.strip() and not l.startswith("#")]


def new_cookware(recipes: list[dict]) -> list[str]:
    p = HERE / "cookware.txt"
    return [l.strip() for l in p.read_text(encoding="utf-8").splitlines() if l.strip() and not l.startswith("#")] if p.exists() else []


TEMPLATE = r"""-- GENERATED by scripts/originals/build.py -- do not edit.
--
-- Wave 12: __COUNT__ "Minced original" recipes (AI-drafted, source_name = 'Minced original'),
-- landing as status 'in_review' so the owner approves them in /admin/review. Nothing here is public.
--
-- PREREQUISITES: all migrations, supabase/seed-ingredients-w12.sql (new vocabulary), and the wave 10c seeds.
-- NEW SLUGS ONLY: a slug that already exists is left strictly alone (an approved or edited recipe is never reset).
-- STRICT: unresolved/fuzzy ingredient, unknown unit/cuisine/cookware, slug owned by another source, or a title
-- that already exists under another slug aborts the whole file.
-- Allergens, diets and nutrition are computed by the database functions at the end, never typed.

begin;
set local jit = off;

__CUISINES__
__COOKWARE__

create temp table _payload (doc jsonb) on commit drop;
insert into _payload values ($minced$__PAYLOAD__$minced$::jsonb);

create temp table _r on commit drop as
select
  r->>'slug' as slug, r->>'title' as title, r->>'cuisine' as cuisine,
  (r->>'prep_time_min')::int as prep_time_min, (r->>'cook_time_min')::int as cook_time_min,
  (r->>'servings')::int as servings, (r->>'spice_level')::smallint as spice_level,
  nullif(r->>'notes','') as notes, r->'cookware' as cookware, r->'steps' as steps
from _payload p, jsonb_array_elements(p.doc) r;

create temp table _l on commit drop as
select
  r->>'slug' as slug, (l->>'sort_order')::int as sort_order, l->>'name' as raw_name,
  (l->>'quantity')::numeric as quantity, nullif(l->>'unit','') as raw_unit,
  nullif(l->>'prep_note','') as prep_note, (l->>'is_optional')::boolean as is_optional
from _payload p, jsonb_array_elements(p.doc) r, jsonb_array_elements(r->'ingredients') l;

create temp table _res on commit drop as
select l.*, ri.ingredient_id, ri.canonical_name, ri.match_kind, ru.unit_id
from _l l
left join lateral resolve_ingredient(l.raw_name) ri on true
left join lateral resolve_unit(l.raw_unit) ru on true;

do $gate$
declare bad text;
begin
  select string_agg(distinct format('%s: "%s"', slug, raw_name), E'\n  ') into bad from _res where ingredient_id is null;
  if bad is not null then raise exception E'UNRESOLVED ingredients:\n  %', bad; end if;

  select string_agg(distinct format('%s: "%s" resolved by %s to "%s"', slug, raw_name, match_kind, canonical_name), E'\n  ')
    into bad from _res where match_kind not in ('exact','alias');
  if bad is not null then raise exception E'FUZZY/near matches are not allowed:\n  %', bad; end if;

  select string_agg(distinct format('%s: unit "%s"', slug, raw_unit), E'\n  ') into bad from _res where raw_unit is not null and unit_id is null;
  if bad is not null then raise exception E'UNKNOWN units:\n  %', bad; end if;

  select string_agg(distinct format('%s: "%s"', r.slug, r.cuisine), E'\n  ') into bad
    from _r r left join cuisines c on c.name = r.cuisine where c.id is null;
  if bad is not null then raise exception E'UNKNOWN cuisines:\n  %', bad; end if;

  select string_agg(distinct format('%s: "%s"', r.slug, cw), E'\n  ') into bad
    from _r r, jsonb_array_elements_text(r.cookware) cw left join cookware k on k.name = cw where k.id is null;
  if bad is not null then raise exception E'UNKNOWN cookware:\n  %', bad; end if;

  select string_agg(r.slug, ', ') into bad from _r r join recipes x on x.slug = r.slug
    where x.source_name is distinct from __SOURCE_NAME__;
  if bad is not null then raise exception 'slug already used by a different source: %', bad; end if;

  select string_agg(format('%s ~ %s', r.slug, x.slug), ', ') into bad
    from _r r join recipes x on lower(x.title) = lower(r.title) and x.slug <> r.slug;
  if bad is not null then raise exception 'title already exists under another slug: %', bad; end if;
end
$gate$;

-- only slugs that do not exist yet
create temp table _new on commit drop as
select r.slug from _r r where not exists (select 1 from recipes x where x.slug = r.slug);

insert into recipes (slug, title, cuisine_id, status, prep_time_min, cook_time_min, servings, spice_level, notes, source_name, source_license)
select r.slug, r.title, c.id, 'in_review', r.prep_time_min, r.cook_time_min, r.servings, r.spice_level, r.notes,
       __SOURCE_NAME__, __SOURCE_LICENSE__
from _r r join cuisines c on c.name = r.cuisine join _new n on n.slug = r.slug;

insert into recipe_ingredients (recipe_id, ingredient_id, quantity, unit_id, prep_note, is_optional, sort_order)
select rc.id, x.ingredient_id, x.quantity, x.unit_id, x.prep_note, x.is_optional, x.sort_order
from _res x join _new n on n.slug = x.slug join recipes rc on rc.slug = x.slug;

insert into recipe_steps (recipe_id, sort_order, instruction)
select rc.id, s.n::int, s.t
from _r r join _new n on n.slug = r.slug join recipes rc on rc.slug = r.slug,
     lateral jsonb_array_elements_text(r.steps) with ordinality s(t, n);

insert into recipe_cookware (recipe_id, cookware_id)
select rc.id, k.id
from _r r join _new n on n.slug = r.slug join recipes rc on rc.slug = r.slug,
     lateral jsonb_array_elements_text(r.cookware) cw join cookware k on k.name = cw;

-- Allergens (trigger-synced already), diets and nutrition: computed by the wave 10/10c functions.
do $refresh$
declare r record;
begin
  for r in select rc.id from recipes rc join _new n on n.slug = rc.slug loop
    perform refresh_recipe_allergens(r.id);
    perform refresh_recipe_diets(r.id);
    perform refresh_recipe_nutrients(r.id);
  end loop;
end
$refresh$;

select (select count(*) from _r) as in_payload, (select count(*) from _new) as inserted,
       (select count(*) from recipes where source_name = __SOURCE_NAME__) as originals_total;

commit;
"""


def main() -> int:
    recipes = bo.parse_recipes()
    sources = bo.parse_sources()
    bo.validate(recipes, sources)
    payload = [
        {k: r[k] for k in ("slug", "title", "cuisine", "prep_time_min", "cook_time_min", "servings", "spice_level",
                           "cookware", "notes", "ingredients", "steps")}
        for r in recipes
    ]
    doc = json.dumps(payload, ensure_ascii=False)
    assert "$minced$" not in doc
    cu = new_cuisines()
    cuisine_sql = ("insert into cuisines (name, slug) values\n  " +
                   ",\n  ".join(f"({bo.sql_text(c)}, {bo.sql_text(slugify(c))})" for c in cu) +
                   "\non conflict (name) do nothing;") if cu else ""
    cw = new_cookware(recipes)
    cookware_sql = ("insert into cookware (name, slug) values\n  " +
                    ",\n  ".join(f"({bo.sql_text(c)}, {bo.sql_text(slugify(c))})" for c in cw) +
                    "\non conflict (name) do nothing;") if cw else ""
    sql = (TEMPLATE.replace("__COUNT__", str(len(recipes)))
           .replace("__CUISINES__", cuisine_sql).replace("__COOKWARE__", cookware_sql)
           .replace("__SOURCE_NAME__", bo.sql_text(SOURCE_NAME))
           .replace("__SOURCE_LICENSE__", bo.sql_text(SOURCE_LICENSE))
           .replace("__PAYLOAD__", doc))
    OUT_SQL.write_text(sql, encoding="utf-8", newline="\n")
    print(f"wrote {OUT_SQL.relative_to(ROOT)} ({len(recipes)} recipes)")

    OUT_REVIEW.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Wave 12 original recipes -- review sheet", "",
             "> GENERATED by `scripts/originals/build.py`. Edit `scripts/originals/recipes/*.txt` and `sources/*.tsv`.", "",
             "All recipes are written in Minced's own words and land as `in_review` (approve in /admin/review).",
             "The URLs are verification only (two independent domains per dish); they are not stored in the database.",
             "Verification method and limits: see `scripts/originals/README.md`.", "",
             f"**{len(recipes)} recipes.**", "",
             "| # | Title | Cuisine | Time | Serves | Spice | Verification sources |", "|---|---|---|---|---|---|---|"]
    for i, r in enumerate(sorted(recipes, key=lambda x: (x["cuisine"], x["title"])), 1):
        urls = " <br> ".join(f"[{j + 1}]({u})" for j, u in enumerate(sources[r["slug"]]))
        lines.append(f"| {i} | {r['title']} | {r['cuisine']} | {r['prep_time_min'] + r['cook_time_min']} min | {r['servings']} | {r['spice_level']} | {urls} |")
    OUT_REVIEW.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
