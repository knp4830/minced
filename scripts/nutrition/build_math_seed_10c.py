#!/usr/bin/env python3
"""Wave 10c: splice the reviewed CSVs into supabase/seed-nutrition-zzzzz-math-10c.sql.

    python -I scripts/nutrition/build_math_seed_10c.py

Three generated blocks, each between BEGIN/END markers in the seed (the rest of the seed is hand-written):
    QUALIFIER FOODS    scripts/nutrition/review/qualifier-foods-10c.csv    (ingredient, form, fdc_id, copy_portions, ...)
    SIZE FACTORS       scripts/nutrition/review/size-factors-10c.csv       (ingredient, size, factor, ...)
    RECIPE LINE FIXES  scripts/nutrition/review/recipe-line-fixes-10c.csv  (slug, sort_order, ingredient, action, ...)
Nothing here talks to a database.
"""
import csv
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SQL = os.path.join(HERE, "..", "..", "supabase", "seed-nutrition-zzzzz-math-10c.sql")
REVIEW = os.path.join(HERE, "review")

ACTIONS = {"note", "ingredient", "qty_unit", "optional", "delete"}


def lit(s):
    return "'" + str(s).replace("'", "''") + "'"


def read(name):
    with open(os.path.join(REVIEW, name), encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def splice(text, tag, body):
    begin = f"-- BEGIN {tag} (generated by scripts/nutrition/build_math_seed_10c.py; edit the CSV, not this block)\n"
    end = f"-- END {tag}\n"
    a, b = text.index(begin) + len(begin), text.index(end)
    return text[:a] + body + text[b:]


def qualifier_block(rows):
    out = []
    for r in rows:
        assert r["ingredient"] and r["form"] and r["fdc_id"].strip().isdigit(), r
        # yes = copy the default form's weights; no = none; any other word = copy that form's weights (cooked, canned...)
        assert r["copy_portions"].isidentifier() and r["copy_portions"].islower(), r
        out.append(f"  ({lit(r['ingredient'])}, {lit(r['form'])}, {int(r['fdc_id'])}, {lit(r['copy_portions'])}, {lit(r.get('why', ''))})")
    return "insert into _q (ingredient, form, fdc_id, copy_portions, why) values\n" + ",\n".join(out) + ";\n" if out else "-- (none)\n"


def port_block(rows):
    out = []
    for r in rows:
        assert r["ingredient"] and r["form"] and float(r["grams"]) > 0 and r["source"] in ("usda", "curated", "us_can_size", "label"), r
        unit = lit(r["unit"]) if r["unit"].strip() else "null"
        out.append(f"  ({lit(r['ingredient'])}, {lit(r['form'])}, {unit}, {float(r['grams']):g}, {lit(r['source'])}, {lit(r['note'])})")
    return "insert into _port (ingredient, form, unit, grams, source, note) values\n" + ",\n".join(out) + ";\n" if out else "-- (none)\n"


def size_block(rows):
    out = []
    for r in rows:
        assert r["size"] in ("small", "medium", "large", "extra large", "jumbo") or re.fullmatch(r"\d{1,2} inch", r["size"]), r
        out.append(f"  ({lit(r['ingredient'])}, {lit(r['size'])}, {float(r['factor']):.4f}, {lit(r.get('source', ''))})")
    return "insert into _size (ingredient, size, factor, source) values\n" + ",\n".join(out) + ";\n" if out else "-- (none)\n"


def fix_block(rows):
    out = []
    for r in rows:
        a = r["action"]
        assert a in ACTIONS, r
        out.append(
            "  (" + ", ".join([lit(r["slug"]), str(int(r["sort_order"])), lit(r["ingredient"]), lit(a), lit(r["old_value"]), lit(r["new_value"])]) + ")"
        )
    return "insert into _fix (slug, ord, ingredient, action, old_value, new_value) values\n" + ",\n".join(out) + ";\n" if out else "-- (none)\n"


def main():
    s = open(SQL, encoding="utf-8").read()
    q = read("qualifier-foods-10c.csv")
    sz = read("size-factors-10c.csv")
    fx = read("recipe-line-fixes-10c.csv")
    s = splice(s, "QUALIFIER FOODS", qualifier_block(q))
    s = splice(s, "EXTRA PORTIONS", port_block(read("extra-portions-10c.csv")))
    s = splice(s, "SIZE FACTORS", size_block(sz))
    s = splice(s, "RECIPE LINE FIXES", fix_block(fx))
    with open(SQL, "w", encoding="utf-8", newline="\n") as f:
        f.write(s)
    print(f"{len(q)} qualifier foods, {len(sz)} size factors, {len(fx)} recipe line fixes written", file=sys.stderr)


if __name__ == "__main__":
    main()
