"""Fetch specific FoodData Central foods (by fdc_id) from the API and write them as a seed: supabase/seed-nutrition-zy-replacements.sql.

Used when a correction needs a REPLACEMENT food that the data does not already hold (a bad default is dropped and a better
record exists in FDC). Branded or generic, CC0. Nutrients go through quality.sane_nutrients (impossible values are left
absent, never 0) and are keyed by the 4-digit FDC nutrient id, joined to nutrients.fdc_nutrient_id like every other seed.

    python -I scripts/nutrition/corrections/add_foods.py 2305175
"""
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))
sys.path.insert(0, os.path.join(HERE, "..", "..", "world-ingredients"))
import fetch_branded as fb  # noqa: E402
from fdc import load_api_key  # noqa: E402
from quality import sane_nutrients  # noqa: E402

OUT = os.path.join(HERE, "..", "..", "..", "supabase", "seed-nutrition-zy-replacements.sql")
# FDC nutrient ids we store (matches nutrients.fdc_nutrient_id), energy fallbacks excluded: branded foods report 1008.
KEEP = {1008, 1003, 1005, 1004, 1079, 2000, 1235, 1257, 1258, 1292, 1293, 1253, 1093, 1092, 1087, 1089, 1090, 1095, 1091, 1103, 1098,
        1101, 1106, 1162, 1114, 1109, 1185, 1165, 1166, 1167, 1175, 1190, 1178, 1170, 1180, 1110}


def iso(d):
    """FDC gives 2022-04-09 or 4/9/2022; the seed wants ISO so DateStyle never matters."""
    if not d:
        return None
    if "/" in d:
        m, day, y = d.split("/")
        return "%04d-%02d-%02d" % (int(y), int(m), int(day))
    return d[:10]


def lit(v):
    return "null" if v in (None, "") else "'" + str(v).replace("'", "''") + "'"


def main():
    ids = [int(x) for x in sys.argv[1:]]
    key = load_api_key()
    if not key:
        raise SystemExit("USDA_FDC_API_KEY not found")
    foods, nuts = [], []
    for i in ids:
        d = fb.get(f"/food/{i}", {}, key)
        m = {}
        for fn in d.get("foodNutrients", []):
            n = fn.get("nutrient") or {}
            if n.get("id") in KEEP and fn.get("amount") is not None:
                m[int(n["id"])] = float(fn["amount"])
        m = sane_nutrients(m)
        foods.append("(%d, %s, 'branded', %s, %s, %s, %s, %s, %s)" % (
            i, lit(d["description"]), lit(d.get("brandOwner")), lit(d.get("brandName")), d.get("servingSize") or "null",
            lit((d.get("servingSizeUnit") or "g").lower().replace("grm", "g")), lit(d.get("householdServingFullText")),
            lit(iso(d.get("publishedDate") or d.get("modifiedDate")))))
        nuts.append("(%d, '%s'::jsonb)" % (i, json.dumps({str(k): round(v, 4) for k, v in m.items()})))
        time.sleep(0.7)
    sql = ["-- Wave 10 fixer: replacement foods for corrected defaults. Generated by scripts/nutrition/corrections/add_foods.py from the",
           "-- FoodData Central API (CC0). IDEMPOTENT. Run after seed-nutrition-zz-integration.sql and BEFORE seed-nutrition-zzz-corrections.sql.",
           "begin;",
           "insert into usda_foods (fdc_id, description, data_type, brand_owner, brand_name, serving_size, serving_size_unit, household_serving, publication_date)\nvalues\n  "
           + ",\n  ".join(foods) + "\non conflict (fdc_id) do nothing;",
           "insert into usda_food_nutrients (fdc_id, nutrient_id, amount_per_100g)\nselect v.fdc_id, n.id, e.value::numeric\nfrom (values\n  "
           + ",\n  ".join(nuts) + "\n) v(fdc_id, j) cross join lateral jsonb_each_text(v.j) e\njoin nutrients n on n.fdc_nutrient_id = e.key::int\non conflict (fdc_id, nutrient_id) do nothing;",
           "commit;"]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(sql) + "\n")
    print("wrote", len(ids), "foods")


main()
