#!/usr/bin/env python3
"""Builds supabase/seed-cookware.sql from the two reviewed data files.

    python scripts/cookware/build.py

Inputs (the source of truth, reviewed by hand, tab separated, '#' = comment):
  assignments.tsv   recipe_slug <TAB> cookware slugs (comma separated, or 'none')
  step_edits.tsv    recipe_slug <TAB> sort_order <TAB> old text <TAB> new text

Output: supabase/seed-cookware.sql, generated -- do not edit it by hand.

Python stdlib only. Files are read as UTF-8 and written with LF endings (Windows
default encodings corrupt the degree signs and accents in recipe text).
"""
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent.parent / "supabase" / "seed-cookware.sql"


def rows(name, ncols):
    out = []
    for n, line in enumerate((HERE / name).read_text(encoding="utf-8").split("\n"), 1):
        if not line.strip() or line.startswith("#"):
            continue
        cols = line.rstrip("\r").split("\t")
        if len(cols) != ncols:
            sys.exit(f"{name}:{n}: expected {ncols} tab-separated columns, got {len(cols)}")
        out.append(cols)
    return out


def q(s):
    """Dollar-quote a text literal so apostrophes need no escaping."""
    if "$q$" in s:
        sys.exit("text contains the $q$ delimiter: " + s)
    return f"$q${s}$q$"


assign = rows("assignments.tsv", 2)
edits = rows("step_edits.tsv", 4)

pairs = []
for slug, cw in assign:
    for c in ([] if cw == "none" else cw.split(",")):
        pairs.append((slug, c.strip()))

seen = set()
for slug, cw in assign:
    if slug in seen:
        sys.exit(f"duplicate recipe in assignments.tsv: {slug}")
    seen.add(slug)

edit_keys = set()
for slug, pos, old, new in edits:
    if (slug, pos) in edit_keys:
        sys.exit(f"duplicate edit for {slug} step {pos}")
    edit_keys.add((slug, pos))
    if old == new:
        sys.exit(f"edit changes nothing: {slug} step {pos}")

sql = []
w = sql.append
w("""-- GENERATED by scripts/cookware/build.py from scripts/cookware/assignments.tsv and
-- scripts/cookware/step_edits.tsv -- do not edit by hand.
--
-- Wave 5 / cookware backfill: recipe_cookware rows for the whole catalog, plus the
-- minimal step edits that make an implied tool explicit ("Simmer 20 min" ->
-- "Simmer in a pot 20 min").
--
-- PREREQUISITE: migration 20261013100000_cookware_vocabulary.sql (the new
-- cookware rows) and 20261012120000_admin_review.sql (recipe_reviews).
--
-- IDEMPOTENT: a re-run changes nothing. Step edits are keyed by (recipe slug,
-- sort_order) and GUARDED on the old text: current text = new text -> skipped;
-- current text = old text -> updated; anything else -> the whole file aborts, so
-- a recipe someone has edited since is never silently overwritten. recipe_cookware
-- rows insert with ON CONFLICT DO NOTHING. The file is ADDITIVE: it never deletes a
-- cookware row.
--
-- STRICT: an unknown recipe slug or cookware slug aborts the file.
--
-- REVIEW RESET: a recipe whose step text was edited goes back to unreviewed in the
-- admin queue (its recipe_reviews row is removed; a rejected recipe is restored to
-- its prior status first, exactly as admin_set_review(..., 'unreviewed') does).
-- Because the edits only apply once, a later re-run does not undo a new approval.
--
-- Writes with the table owner / service role only (it bypasses RLS on purpose).

begin;

create temp table _cw_edit (slug text, pos int, old_text text, new_text text) on commit drop;
""")

if edits:
    w("insert into _cw_edit (slug, pos, old_text, new_text) values")
    w(",\n".join(f"  ({q(s)}, {int(p)}, {q(o)}, {q(n)})" for s, p, o, n in edits) + ";")
    w("")

w("""create temp table _cw_edited (recipe_id uuid primary key) on commit drop;

do $$
declare
  e      record;
  cur    text;
  rid    uuid;
  n_new  int := 0;
  n_skip int := 0;
begin
  for e in select * from _cw_edit order by slug, pos loop
    select r.id, s.instruction into rid, cur
    from   recipes r
    join   recipe_steps s on s.recipe_id = r.id and s.sort_order = e.pos
    where  r.slug = e.slug;

    if rid is null then
      raise exception 'step edit target not found: % step %', e.slug, e.pos;
    elsif cur = e.new_text then
      n_skip := n_skip + 1;                       -- already applied
    elsif cur = e.old_text then
      update recipe_steps set instruction = e.new_text
      where  recipe_id = rid and sort_order = e.pos;
      insert into _cw_edited values (rid) on conflict do nothing;
      n_new := n_new + 1;
    else
      raise exception 'step text changed since review, refusing to overwrite: % step % (now: %)',
        e.slug, e.pos, cur;
    end if;
  end loop;
  raise notice 'step edits: % applied, % already applied', n_new, n_skip;
end $$;

-- Edited recipes go back to unreviewed. Rejected ones are restored to their prior
-- status first (reject only ever set status = draft and remembered the old one).
update recipes r
set    status = coalesce(rv.prior_status, 'published')
from   recipe_reviews rv
join   _cw_edited x on x.recipe_id = rv.recipe_id
where  rv.recipe_id = r.id and rv.review_status = 'rejected';

delete from recipe_reviews where recipe_id in (select recipe_id from _cw_edited);

create temp table _cw_pair (slug text, cookware text) on commit drop;
""")

if pairs:
    w("insert into _cw_pair (slug, cookware) values")
    w(",\n".join(f"  ('{s}', '{c}')" for s, c in pairs) + ";")
    w("")

w("""do $$
declare
  bad text;
  n   int;
begin
  select string_agg(distinct p.slug, ', ') into bad
  from   _cw_pair p left join recipes r on r.slug = p.slug where r.id is null;
  if bad is not null then raise exception 'unknown recipe slug(s): %', bad; end if;

  select string_agg(distinct p.cookware, ', ') into bad
  from   _cw_pair p left join cookware c on c.slug = p.cookware where c.id is null;
  if bad is not null then raise exception 'unknown cookware slug(s): %', bad; end if;

  insert into recipe_cookware (recipe_id, cookware_id)
  select r.id, c.id
  from   _cw_pair p
  join   recipes  r on r.slug = p.slug
  join   cookware c on c.slug = p.cookware
  on conflict do nothing;
  get diagnostics n = row_count;
  raise notice 'recipe_cookware: % rows inserted', n;
end $$;

commit;
""")

OUT.write_text("\n".join(sql), encoding="utf-8", newline="\n")
print(f"wrote {OUT} ({len(pairs)} cookware pairs, {len(edits)} step edits, {len(assign)} recipes reviewed)")
