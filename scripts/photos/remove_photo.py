#!/usr/bin/env python3
"""Remove a photo (any source) at its SOURCE manifest so process_images.py cannot bring it back.

    python scripts/photos/remove_photo.py <slug> "reason" [--bucket wave4_review_2026_10_12]

process_images.py rebuilds manifest/photos.json from myplate.json + commons.json, so editing
photos.json alone is undone on the next run. This drops the row from commons.json and from the
picks files (so a rebuild does not re-add it) and records WHY in commons_r2_rejected.json, so nobody
re-reviews the same file. Regenerate afterwards:
    python scripts/photos/process_images.py && python scripts/photos/apply_manifest.py > supabase/seed-photos.sql
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import MANIFEST_DIR, picks_files, write_json  # noqa: E402


def load(name: str, default=None):
    f = MANIFEST_DIR / name
    return json.loads(f.read_text(encoding="utf-8")) if f.exists() else ([] if default is None else default)


MANIFESTS = ("commons.json", "openverse.json", "pexels.json")   # row lists; myplate.json is rebuilt from myplate_review_excludes.json


def main() -> None:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    bucket = "wave4_review_2026_10_12"
    if "--bucket" in sys.argv:
        bucket = sys.argv[sys.argv.index("--bucket") + 1]
        args = [a for a in args if a != bucket]
    slug, reason = args[0], args[1]
    # USDA MyPlate photos are regenerated by myplate_audit.py, so the durable record is the excludes file.
    mp = load("myplate.json")
    if any(r["slug"] == slug for r in mp):
        ex = load("myplate_review_excludes.json", {})
        ex[slug] = reason
        write_json(MANIFEST_DIR / "myplate_review_excludes.json", ex)
        write_json(MANIFEST_DIR / "myplate.json", [r for r in mp if r["slug"] != slug])
        print(f"removed {slug} (usda_myplate); recorded in myplate_review_excludes.json")
        return
    for name in MANIFESTS:
        rows = load(name)
        removed = next((r for r in rows if r["slug"] == slug), None)
        if removed:
            break
    else:
        sys.exit(f"{slug}: not in any manifest ({', '.join(MANIFESTS)}, myplate.json)")
    write_json(MANIFEST_DIR / name, [r for r in rows if r["slug"] != slug])
    for pf in picks_files():   # every *picks*.json (r15, w4, w7, openverse ...), so no rebuild can re-add the photo
        picks = json.loads(pf.read_text(encoding="utf-8"))
        if slug in picks:
            del picks[slug]
            write_json(pf, picks)
    rej = load("commons_r2_rejected.json", {})
    rej.setdefault(bucket, {})[slug] = f"{removed.get('file') or removed.get('attribution_url')}: {reason}"
    write_json(MANIFEST_DIR / "commons_r2_rejected.json", rej)
    print(f"removed {slug} ({removed.get('file') or removed.get('attribution_url')}) from {name}")


if __name__ == "__main__":
    main()
